BEGIN;

DO $$
BEGIN
  IF to_regclass('public.jizdni_rady') IS NOT NULL
     OR to_regclass('public.mobile_course_visibility') IS NOT NULL
  THEN
    RAISE EXCEPTION 'Migrace odmítnuta: cílová tabulka již existuje.';
  END IF;
END;
$$;

CREATE TABLE public.jizdni_rady (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_number text,
  course_number text,
  transport_type text,
  day_type text,
  image_url text,
  image_path text,
  keywords text,
  part_of_day text
);

CREATE TABLE public.mobile_course_visibility (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  line_number text NOT NULL,
  course_number text NOT NULL,
  transport_type text NOT NULL,
  day_type text NOT NULL,
  UNIQUE (line_number, course_number, transport_type, day_type)
);

CREATE OR REPLACE FUNCTION public.mobile_can_read_course(
  p_line text,
  p_course text,
  p_transport text,
  p_day text
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.profiles p
    WHERE p.id = (SELECT auth.uid())
      AND p.status = 'approved'
      AND p.is_blocked = false
      AND (
        p.role = 'admin'
        OR (
          p.role = 'user'
          AND EXISTS (
            SELECT 1
            FROM public.mobile_course_visibility v
            WHERE v.line_number = p_line
              AND v.course_number = p_course
              AND v.transport_type = p_transport
              AND v.day_type = p_day
          )
        )
      )
  );
$$;

ALTER TABLE public.jizdni_rady ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mobile_course_visibility ENABLE ROW LEVEL SECURITY;

CREATE POLICY jizdni_rady_member_read
ON public.jizdni_rady
AS PERMISSIVE
FOR SELECT
TO authenticated
USING (
  EXISTS (
    SELECT 1
    FROM public.profiles p
    WHERE p.id = (SELECT auth.uid())
      AND p.status = 'approved'
      AND p.is_blocked = false
      AND p.role IN ('admin', 'user')
  )
);

CREATE POLICY jizdni_rady_course_visibility
ON public.jizdni_rady
AS RESTRICTIVE
FOR SELECT
TO authenticated
USING (
  public.mobile_can_read_course(
    line_number,
    course_number,
    transport_type,
    day_type
  )
);

REVOKE ALL ON public.jizdni_rady FROM PUBLIC, anon;
GRANT SELECT ON public.jizdni_rady TO authenticated;

REVOKE ALL ON public.mobile_course_visibility
FROM PUBLIC, anon, authenticated;

REVOKE ALL ON FUNCTION public.mobile_can_read_course(
  text, text, text, text
) FROM PUBLIC;

GRANT EXECUTE ON FUNCTION public.mobile_can_read_course(
  text, text, text, text
) TO authenticated;

COMMIT;
